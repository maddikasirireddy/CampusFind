-- CampusFind Production Database Initialization
-- Safe and idempotent: creates tables, constraints, indexes, triggers and initial migrations
-- Run against your hosted PostgreSQL instance (e.g., Render PostgreSQL):
-- psql "$DATABASE_URL" -f database/init_production.sql

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ─────────────────────────────────────────────
--  USERS
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
  id          SERIAL PRIMARY KEY,
  name        VARCHAR(120) NOT NULL,
  email       VARCHAR(254) NOT NULL UNIQUE,
  password    VARCHAR(255) NOT NULL,
  student_id  VARCHAR(50)  NOT NULL UNIQUE,
  phone       VARCHAR(20),
  role        VARCHAR(10)  NOT NULL DEFAULT 'student' CHECK (role IN ('student','admin')),
  avatar_url  TEXT,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ─────────────────────────────────────────────
--  ITEM CATEGORIES (lookup)
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS categories (
  id    SERIAL PRIMARY KEY,
  name  VARCHAR(80) NOT NULL UNIQUE,
  icon  VARCHAR(10) NOT NULL DEFAULT '📦'
);

-- ─────────────────────────────────────────────
--  CAMPUS LOCATIONS (lookup)
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS locations (
  id    SERIAL PRIMARY KEY,
  name  VARCHAR(120) NOT NULL UNIQUE,
  zone  VARCHAR(80)
);

-- ─────────────────────────────────────────────
--  ITEMS (lost or found reports)
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS items (
  id                 SERIAL PRIMARY KEY,
  user_id            INT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type               VARCHAR(10)  NOT NULL CHECK (type IN ('lost','found')),
  title              VARCHAR(200) NOT NULL,
  description        TEXT         NOT NULL,
  category_id        INT          REFERENCES categories(id) ON DELETE SET NULL,
  custom_subcategory VARCHAR(100),
  location_id        INT          REFERENCES locations(id)  ON DELETE SET NULL,
  custom_location    VARCHAR(200),
  date_reported      DATE         NOT NULL DEFAULT CURRENT_DATE,
  date_occurred      DATE,
  status             VARCHAR(20)  NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active','claimed','returned','closed')),
  image_url          TEXT,
  color              VARCHAR(60),
  brand              VARCHAR(100),
  tags               TEXT,
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- Ensure migration columns exist if items table was already created
ALTER TABLE items ADD COLUMN IF NOT EXISTS custom_subcategory VARCHAR(100);
ALTER TABLE items ADD COLUMN IF NOT EXISTS custom_location VARCHAR(200);

CREATE INDEX IF NOT EXISTS idx_items_user    ON items(user_id);
CREATE INDEX IF NOT EXISTS idx_items_type    ON items(type);
CREATE INDEX IF NOT EXISTS idx_items_status  ON items(status);
CREATE INDEX IF NOT EXISTS idx_items_cat     ON items(category_id);
CREATE INDEX IF NOT EXISTS idx_items_loc     ON items(location_id);
CREATE INDEX IF NOT EXISTS idx_items_date    ON items(date_occurred);

-- ─────────────────────────────────────────────
--  MATCHES (auto-generated by matching engine)
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS matches (
  id          SERIAL PRIMARY KEY,
  lost_id     INT          NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  found_id    INT          NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  score       NUMERIC(5,2) NOT NULL DEFAULT 0,
  factors     TEXT,
  status      VARCHAR(20)  NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending','accepted','rejected','expired')),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  UNIQUE (lost_id, found_id)
);

ALTER TABLE matches ADD COLUMN IF NOT EXISTS factors TEXT;

CREATE INDEX IF NOT EXISTS idx_matches_lost  ON matches(lost_id);
CREATE INDEX IF NOT EXISTS idx_matches_found ON matches(found_id);

-- ─────────────────────────────────────────────
--  CLAIMS
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS claims (
  id            SERIAL PRIMARY KEY,
  item_id       INT          NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  claimant_id   INT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message       TEXT,
  proof         TEXT,
  status        VARCHAR(20)  NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending','approved','rejected')),
  admin_note    TEXT,
  resolved_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  UNIQUE (item_id, claimant_id)
);

CREATE INDEX IF NOT EXISTS idx_claims_item      ON claims(item_id);
CREATE INDEX IF NOT EXISTS idx_claims_claimant  ON claims(claimant_id);
CREATE INDEX IF NOT EXISTS idx_claims_status    ON claims(status);

-- ─────────────────────────────────────────────
--  NOTIFICATIONS
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS notifications (
  id          SERIAL PRIMARY KEY,
  user_id     INT          NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type        VARCHAR(40)  NOT NULL,
  title       VARCHAR(200) NOT NULL,
  message     TEXT,
  ref_id      INT,
  ref_type    VARCHAR(20),
  is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notif_user   ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_notif_read   ON notifications(user_id, is_read);

-- ─────────────────────────────────────────────
--  AUDIT / ACTIVITY LOG
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS activity_log (
  id          SERIAL PRIMARY KEY,
  user_id     INT    REFERENCES users(id) ON DELETE SET NULL,
  action      VARCHAR(100) NOT NULL,
  details     TEXT,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ─────────────────────────────────────────────
--  TRIGGER: updated_at updater
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_users_updated ON users;
CREATE TRIGGER trg_users_updated
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_items_updated ON items;
CREATE TRIGGER trg_items_updated
  BEFORE UPDATE ON items
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

